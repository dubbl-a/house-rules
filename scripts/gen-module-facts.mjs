#!/usr/bin/env node
// Generates MODULE_FACTS in plugins/house/payload/check.mjs from
// plugins/house/modules/*/module.json: for each shipped module, the facts that
// are the same for every adopter (default, rule files with their path lists,
// the declared default of each path slot). The checker is vendored byte-identical,
// so these facts reach an adopter's CI without a lock record that a hand edit
// could change (#258).
//
//   node scripts/gen-module-facts.mjs          rewrite the block in check.mjs
//   node scripts/gen-module-facts.mjs --check  exit 1 if the block is stale
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MODULES = join(ROOT, 'plugins', 'house', 'modules');
export const CHECK = join(ROOT, 'plugins', 'house', 'payload', 'check.mjs');
export const BEGIN = '// BEGIN MODULE_FACTS (generated by scripts/gen-module-facts.mjs; do not edit)';
export const END = '// END MODULE_FACTS';

const isObj = (x) => x !== null && typeof x === 'object' && !Array.isArray(x);

// {name -> {default, rules: [{file, paths}], slots: {name -> default globs}}},
// sorted by name. A rule entry is a path (loads on defaultPaths) or
// {file, paths}; one with neither is skipped, as render skips it.
export function buildFacts(modulesDir = MODULES) {
  const out = {};
  for (const ent of readdirSync(modulesDir, { withFileTypes: true })) {
    if (!ent.isDirectory()) continue;
    const mp = join(modulesDir, ent.name, 'module.json');
    if (!existsSync(mp)) continue;
    const j = JSON.parse(readFileSync(mp, 'utf8'));
    const name = (typeof j.name === 'string' && j.name) || ent.name;
    const rules = [];
    for (const r of Array.isArray(j.rules) ? j.rules : []) {
      if (typeof r === 'string') rules.push({ file: basename(r), paths: Array.isArray(j.defaultPaths) ? j.defaultPaths.filter((p) => typeof p === 'string' && p) : [] });
      else if (isObj(r) && typeof r.file === 'string' && r.file && Array.isArray(r.paths)) rules.push({ file: basename(r.file), paths: r.paths.filter((p) => typeof p === 'string' && p) });
    }
    const slots = {};
    for (const s of Array.isArray(j.configSlots) ? j.configSlots : []) {
      if (typeof s === 'string' && s) slots[s] = [];
      else if (isObj(s) && typeof s.name === 'string' && s.name) slots[s.name] = Array.isArray(s.default) ? s.default.filter((p) => typeof p === 'string') : [];
    }
    out[name] = { default: j.default === 'off' || j.default === 'detect' ? j.default : 'on', rules, slots };
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

export function renderBlock(facts = buildFacts()) {
  const lines = Object.entries(facts).map(([n, f]) => `  ${JSON.stringify(n)}: ${JSON.stringify(f)},`);
  return `${BEGIN}\nconst MODULE_FACTS = {\n${lines.join('\n')}\n};\n${END}`;
}

export function splice(source, block) {
  const a = source.indexOf(BEGIN);
  const b = source.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error('MODULE_FACTS markers not found in check.mjs');
  return source.slice(0, a) + block + source.slice(b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = readFileSync(CHECK, 'utf8');
  const next = splice(src, renderBlock());
  if (process.argv.includes('--check')) {
    if (next !== src) { console.error('MODULE_FACTS in check.mjs is stale; run: node scripts/gen-module-facts.mjs'); process.exit(1); }
  } else if (next !== src) {
    writeFileSync(CHECK, next);
    console.log('MODULE_FACTS updated in plugins/house/payload/check.mjs');
  }
}
